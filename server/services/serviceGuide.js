/**
 * server/services/serviceGuide.js
 * 챗봇이 들어 있는 서비스(ONE Student) 자체에 대한 근거 청크.
 *
 * 학생이 "커뮤니티 글 올렸는데 왜 바로 등록이 안 돼?"처럼 이 서비스의 기능을 물으면, 근거가 학칙 문서뿐이라 챗봇이 학교
 * 커뮤니티로 알아듣고 "웹정보서비스 운영 부서나 학교 전산 부서에 문의하라"고 답했다(2026-10-22 사용자 피드백). 근거를 하나도
 * 못 찾으면 AI 호출 없이 고정 안내로 끝나기도 해서, 서비스 기능을 말하는 질문에는 이 안내를 근거로 함께 넣는다.
 * 내용은 화면 동작과 같아야 한다 — 커뮤니티 승인·과목 가져오기 방식이 바뀌면 여기도 고친다.
 */

// 이 서비스의 화면·기능을 가리키는 표현. "신고"·"알림"처럼 학사와 거의 안 겹치는 것만 넣는다.
const SERVICE_TOPIC_RE = /커뮤니티|게시글|게시판|글\s*(을|이|좀)?\s*(올|등록|썼|쓰)|과목\s*관리|졸업요건\s*진단|진로\s*탐색|문의하기|ONE\s*Student|원\s*스튜던트|이\s*(앱|서비스|사이트)|로그인|회원\s*탈퇴|닉네임|스터디|팀원|공모전|신고|제재/i;

const SERVICE_GUIDE_CHUNK = {
  chunkId: 'service-guide',
  documentTitle: 'ONE Student 이용 안내',
  content: [
    'ONE Student는 원광대학교 학생을 위한 비공식 학생 서비스이고, 이 챗봇은 그 안에 있다. 학교 웹정보서비스(인트라넷)와는 다른 서비스다.',
    '메뉴: 과목 관리, 졸업요건 진단, 진로 탐색, 커뮤니티, 문의하기, 채팅(이 챗봇).',
    '커뮤니티: 스터디·팀 활동·공모전 팀원을 구하는 게시판이다. 새로 쓴 글과 수정한 글은 운영자가 확인(승인)한 뒤에 전체 글 목록에 보인다. 글을 올린 직후 목록에 안 보이면 승인을 기다리는 중이다. 승인 상태는 커뮤니티 → "내가 쓴 글" 탭에서 볼 수 있고, 반려되면 반려 사유도 함께 보인다.',
    '과목 관리: 들은 과목을 직접 넣거나, 웹정보서비스의 전체성적조회·이수과목확인리스트 화면을 PDF로 저장해 올리면 한 번에 가져온다. 졸업요건 진단과 이 챗봇의 이수 현황은 여기에 등록한 과목으로 계산한다.',
    '이 서비스를 쓰다 생긴 문제(오류, 계정, 커뮤니티 이용, 개선 제안)는 학교 부서가 아니라 ONE Student의 "문의하기" 메뉴로 보내면 운영자가 답한다. 이런 문제를 학사지원과나 학교 전산 부서에 물어보라고 안내하지 마라.',
  ].join('\n'),
};

/** 질문이 이 서비스의 기능을 말하면 안내 청크를 돌려준다. */
function serviceGuideChunks(message) {
  return SERVICE_TOPIC_RE.test(String(message || '')) ? [SERVICE_GUIDE_CHUNK] : [];
}

module.exports = { serviceGuideChunks, SERVICE_GUIDE_CHUNK };
